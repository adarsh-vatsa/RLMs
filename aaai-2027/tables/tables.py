"""Write the paper's tables from the suite results into table1.tex to table4.tex.

Each file holds only the tabular; captions and labels stay in main.tex.
Run from anywhere: uv run aaai-2027/tables/tables.py
"""

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARTIFACTS = HERE.parents[1] / "benchmark_artifacts"
AA_LCR = ARTIFACTS / "aa_lcr/suites/20261029"
MRCR = ARTIFACTS / "mrcr_v2/suites/20261029"
LONGBENCH = ARTIFACTS / "longbench_v2/suites/20261029"

# Benchmark: results table, intervals table, main window, per-answer file of a hybrid condition.
# The intervals come from the markdown table, which rounds the exact bounds; the CSV keeps only 4 decimals.
BENCHMARKS = {
    "AA-LCR": (AA_LCR / "results-gpt-5.6-luna.csv", AA_LCR / "intervals-gpt-5.6-luna.md", 65536,
               lambda c: AA_LCR / f"hybrid/20261029_{c}/execution.jsonl"),
    "MRCR v2": (MRCR / "results.csv", MRCR / "intervals.md", 262144,
                lambda c: MRCR / f"hybrid/20261029_{c}/predictions.jsonl"),
    "LongBench-v2": (LONGBENCH / "results.csv", LONGBENCH / "intervals.md", 65536,
                     lambda c: LONGBENCH / f"longbench_v2/20261029_{c}/execution.jsonl"),
}
# CPU embedding exists only from the 30 September dense runs, with the suite's dense chunking.
CPU_DENSE = {
    "AA-LCR": ARTIFACTS / "aa_lcr/hybrid/20260930T025706Z/execution.jsonl",
    "MRCR v2": ARTIFACTS / "mrcr_v2/hybrid/20260930T172140824150Z/predictions.jsonl",
}
WINDOW_LABELS = {32768: "32K", 65536: "64K", 81920: "80K", 131072: "128K", 262144: "262K"}
GENERATED = "% Generated by aaai-2027/tables/tables.py from benchmark_artifacts; do not edit.\n"


def read_csv(path):
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def results(name):
    return {row["condition"]: row for row in read_csv(BENCHMARKS[name][0])}


def read_markdown(path):
    lines = [line.strip().strip("|").split("|") for line in path.read_text().splitlines() if line.startswith("|")]
    columns = [cell.strip() for cell in lines[0]]
    return [dict(zip(columns, (cell.strip() for cell in line))) for line in lines[2:]]


def number(value, digits=1):
    return f"{value:.{digits}f}"


def signed(text):
    """A signed percentage from a markdown cell such as '-5.1%', with a typeset minus."""
    return text.removesuffix("%").replace("-", "$-$")


def write(name, header, groups):
    """Write a tabular whose row groups are separated by rules."""
    body = " \\\\\n\\midrule\n".join(" \\\\\n".join(rows) for rows in groups)
    (HERE / name).write_text(GENERATED + header + body + " \\\\\n\\bottomrule\n\\end{tabular}\n")


def counts(text):
    """Correct and graded questions from a results cell such as '65/100' or '65/99 (1 invalid)'."""
    correct, graded = text.split()[0].split("/")
    return int(correct), int(graded)


TABLE1_GROUPS = [
    [("Middle truncation", "middle"), ("Middle, marked", "middle_marked"), ("Head only", "head")],
    [("Random chunks", "random0"), ("Position", "position"), ("Position recipe", "position_recipe")],
    [("BM25", "bm25"), ("Dense", "dense"), ("Fusion", "fusion"), ("BM25 recipe", "bm25_recipe"),
     ("Fusion recipe", "upgraded")],
    [("Full context (262K)", "full"), ("Oracle", "oracle")],
]


def table1():
    """Every policy at each benchmark's main window, with the paired difference from middle truncation."""
    columns = []
    for name, (_, intervals, _, _) in BENCHMARKS.items():
        differences = {row["condition"]: row for row in read_markdown(intervals) if row["baseline"] == "middle"}
        columns.append((results(name), differences))
    groups = []
    for group in TABLE1_GROUPS:
        groups.append([])
        for label, condition in group:
            cells = [label]
            for rows, differences in columns:
                if condition not in rows:
                    cells += ["---", ""]
                    continue
                correct, graded = counts(rows[condition]["correct"])
                cells.append(number(100 * correct / graded))
                if condition == "middle":
                    cells.append("")
                else:
                    d = differences[condition]
                    cells.append(f"{signed(d['difference'])} [{signed(d['95% low'])}, {signed(d['95% high'])}]")
            groups[-1].append(" & ".join(cells))
    header = ("\\begin{tabular}{l rl rl rl}\n\\toprule\n"
              + "".join(f" & \\multicolumn{{2}}{{c}}{{{name}, {WINDOW_LABELS[spec[2]]}}}"
                        for name, spec in BENCHMARKS.items())
              + " \\\\\n\\cmidrule(lr){2-3} \\cmidrule(lr){4-5} \\cmidrule(lr){6-7}\n"
              "Policy & Acc. & $\\Delta$ [95\\% CI] & EM & $\\Delta$ [95\\% CI] & Acc. & $\\Delta$ [95\\% CI] \\\\\n"
              "\\midrule\n")
    write("table1.tex", header, groups)


def table2():
    """MRCR visibility decomposition across windows."""
    rows = {row["condition"]: row for row in read_csv(MRCR / "visibility.csv")}
    policies = [("Middle truncation", "middle"), ("BM25", "bm25"), ("BM25 recipe", "bm25_recipe"),
                ("Fusion recipe", "upgraded"), ("Oracle", "oracle")]
    groups = []
    for window in (32768, 65536, 131072, 262144):
        groups.append([f"\\multicolumn{{5}}{{l}}{{\\emph{{{WINDOW_LABELS[window]} window}}}}"])
        suffix = "" if window == 262144 else f"_{WINDOW_LABELS[window].lower()}"
        for label, base in policies:
            if base + suffix not in rows:  # the BM25 recipe did not run at 262K
                continue
            row = rows[base + suffix]
            # The CSV rounds to 4 decimals; recover the question counts so the paper rounds exact rates.
            questions = int(row["questions"])
            visible = round(float(row["target visible"]) * questions)
            needles = round(float(row["all needles visible"]) * questions)
            correct = round(float(row["exact match"]) * questions)
            correct_visible = round(float(row["exact match given target visible"]) * visible)
            # Conditional rates on fewer than 30 questions carry their count.
            given = number(100 * correct_visible / visible) + (f" ({visible})" if visible < 30 else "")
            groups[-1].append(" & ".join([label, number(100 * visible / questions, 0),
                                          number(100 * needles / questions, 0), given,
                                          number(100 * correct / questions)]))
    header = ("\\begin{tabular}{lrrrr}\n\\toprule\n"
              "Policy & Target & Needles & EM $\\mid$ target & EM \\\\\n\\midrule\n")
    write("table2.tex", header, groups)


def embedding_seconds(path):
    """Document embedding time per question, amortized over the questions that share a document index."""
    answers = [json.loads(line) for line in path.open() if line.strip()]
    return sum(a.get("document_embedding_ms") or 0 for a in answers) / len(answers) / 1000


def table3():
    """Time and input tokens per question at each benchmark's main window."""
    policies = [("Full context", "full"), ("Middle truncation", "middle"), ("BM25", "bm25"),
                ("Dense", "dense"), ("Fusion recipe", "upgraded")]
    groups = []
    for name, (_, _, window, answers) in BENCHMARKS.items():
        body = [f"\\multicolumn{{6}}{{l}}{{\\emph{{{name}, {WINDOW_LABELS[window]} window}}}}"]
        groups.append(body)
        rows = results(name)
        for label, condition in policies:
            if condition not in rows:
                continue
            row = rows[condition]
            hybrid = bool(row["retrieval + packing s/question"])
            gpu = embedding_seconds(answers(condition)) if hybrid else 0
            cpu = CPU_DENSE.get(name) if condition == "dense" else None
            body.append(" & ".join([
                label,
                number(float(row["input tokens"]) / 1000),
                number(gpu, 2) if gpu else "---",
                number(embedding_seconds(cpu), 1) if cpu else "---",
                number(float(row["retrieval + packing s/question"]), 2) if hybrid else "---",
                number(float(row["generation s/question"])),
            ]))
    header = ("\\begin{tabular}{lrrrrr}\n\\toprule\n"
              " & Input & \\multicolumn{2}{c}{Embedding (s)} & Select & Generate \\\\\n"
              "\\cmidrule(lr){3-4}\n"
              "Policy & (K tok.) & GPU & CPU & (s) & (s) \\\\\n\\midrule\n")
    write("table3.tex", header, groups)


# The paper's two central questions, tested at every window of every benchmark and corrected together:
# does the recipe beat middle truncation, and does it beat position, which keeps the same structure
# without the question?
PRIMARY_BASELINES = ("middle", "position")


def holm(p_values):
    """Holm-adjusted p-values, in the order given."""
    order = sorted(range(len(p_values)), key=p_values.__getitem__)
    adjusted, running = [0.0] * len(p_values), 0.0
    for rank, index in enumerate(order):
        running = max(running, min(1.0, (len(p_values) - rank) * p_values[index]))
        adjusted[index] = running
    return adjusted


def p_cell(p, significant=False):
    text = "$<$0.001" if p < 0.001 else f"{p:.3f}"
    return f"\\textbf{{{text}}}" if significant else text


def table4():
    """The primary comparisons, with randomization p-values and Holm's correction across all of them."""
    comparisons = []
    for name, (_, intervals, _, _) in BENCHMARKS.items():
        shown = {(row["condition"], row["baseline"]): row for row in read_markdown(intervals)}
        for row in read_csv(intervals.with_suffix(".csv")):
            suffix = row["condition"].removeprefix("upgraded")
            if row["condition"].startswith("upgraded") and row["baseline"] in {b + suffix for b in PRIMARY_BASELINES}:
                comparisons.append((name, int(row["window"]), row["baseline"].removesuffix(suffix), float(row["p"]),
                                    shown[(row["condition"], row["baseline"])]))
    adjusted = holm([p for *_, p, _ in comparisons])
    cells = {(name, window, baseline): (p, holm_p, d)
             for (name, window, baseline, p, d), holm_p in zip(comparisons, adjusted)}
    groups = []
    for name in BENCHMARKS:
        groups.append([f"\\multicolumn{{7}}{{l}}{{\\emph{{{name}}}}}"])
        for window in sorted({window for benchmark, window, _ in cells if benchmark == name}):
            row = [WINDOW_LABELS[window]]
            for baseline in PRIMARY_BASELINES:
                p, holm_p, d = cells[(name, window, baseline)]
                row += [f"{signed(d['difference'])} [{signed(d['95% low'])}, {signed(d['95% high'])}]",
                        p_cell(p), p_cell(holm_p, holm_p < 0.05)]
            groups[-1].append(" & ".join(row))
    header = ("\\begin{tabular}{l lrr lrr}\n\\toprule\n"
              " & \\multicolumn{3}{c}{Against middle truncation} & \\multicolumn{3}{c}{Against position} \\\\\n"
              "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7}\n"
              "Window & $\\Delta$ [95\\% CI] & $p$ & Holm $p$ & $\\Delta$ [95\\% CI] & $p$ & Holm $p$ \\\\\n"
              "\\midrule\n")
    write("table4.tex", header, groups)


if __name__ == "__main__":
    table1()
    table2()
    table3()
    table4()
